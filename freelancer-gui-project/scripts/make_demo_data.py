#!/usr/bin/env python3
"""
Generates database/sample_data.sql: demo freelancers, clients, projects, logged time,
invoices and messages, so the app can be tried straight away.

Passwords are hashed exactly like the Java app does it (PBKDF2-HMAC-SHA256, 65536
iterations, random 16-byte salt, stored as iterations:salt:hash in Base64), so the demo
accounts can really log in. Every demo account uses the password  demo1234.

Usage:   python scripts/make_demo_data.py
"""
import base64
import hashlib
import os
from datetime import date, datetime, timedelta

PASSWORD = "demo1234"
ITERATIONS = 65536
TODAY = date.today()


def hash_password(password: str) -> str:
    salt = os.urandom(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, ITERATIONS, dklen=32)
    return f"{ITERATIONS}:{base64.b64encode(salt).decode()}:{base64.b64encode(digest).decode()}"


def q(text: str) -> str:
    """Quote a value for SQL."""
    return "'" + text.replace("'", "''") + "'"


def uid(email: str) -> str:
    return f"(SELECT id FROM users WHERE email = {q(email)})"


def pid(name: str) -> str:
    return f"(SELECT id FROM projects WHERE name = {q(name)})"


def stamp(days_ago: int, hour: int, minutes: int = 0) -> datetime:
    day = TODAY - timedelta(days=days_ago)
    return datetime(day.year, day.month, day.day, hour, minutes)


FREELANCERS = [
    ("Sara Ahmed", "sara@example.com"),
    ("Rohan Mehta", "rohan@example.com"),
    ("Lena Fischer", "lena@example.com"),
]
CLIENTS = [("Acme Corp", "acme@example.com"), ("Bright Studio", "bright@example.com")]

# name, description, deadline offset (days), status, freelancer, client
PROJECTS = [
    ("Website Redesign", "New marketing site", 2, "IN_PROGRESS", "sara@example.com", "acme@example.com"),
    ("Mobile App MVP", "First release of the app", 21, "NOT_STARTED", "sara@example.com", "bright@example.com"),
    ("Brand Guidelines", "Logo, colours and fonts", -3, "IN_PROGRESS", "rohan@example.com", "acme@example.com"),
    ("SEO Audit", "Technical and content audit", -10, "COMPLETED", "lena@example.com", "bright@example.com"),
    ("Data Dashboard", "Sales dashboard for management", 12, "IN_PROGRESS", "rohan@example.com", "bright@example.com"),
]

# project, days ago, start hour, hours worked
TIME = [
    ("Website Redesign", 0, 9, 3.5), ("Website Redesign", 1, 10, 4.0), ("Website Redesign", 3, 9, 2.5),
    ("Mobile App MVP", 4, 14, 1.5), ("Brand Guidelines", 2, 9, 5.0), ("Brand Guidelines", 5, 13, 3.0),
    ("Data Dashboard", 1, 8, 6.0), ("Data Dashboard", 2, 8, 5.5), ("SEO Audit", 9, 9, 6.0), ("SEO Audit", 11, 9, 6.5),
]

# project, type, hours, rate, status, days ago
INVOICES = [
    ("SEO Audit", "HOURLY", 12.5, 40.0, "PAID", 8),
    ("Brand Guidelines", "HOURLY", 8.0, 45.0, "PENDING", 2),
    ("Website Redesign", "FIXED", 10.0, 600.0, "PENDING", 1),
]

MESSAGES = [
    ("acme@example.com", "sara@example.com", "Could we move the review meeting to Friday?", 0, 9, False),
    ("bright@example.com", "sara@example.com", "Thanks for the update, looks great!", 1, 16, False),
    ("sara@example.com", "acme@example.com", "The draft designs are ready for review.", 2, 11, True),
]


def main() -> None:
    out = [
        "-- Demo data for Time Management for Freelancers",
        f"-- Generated by scripts/make_demo_data.py on {TODAY}.",
        "-- Run the app once first (it creates the tables), close it, then load this file.",
        f"-- Every demo account has the password: {PASSWORD}",
        "",
    ]
    for name, email in FREELANCERS:
        out.append(f"INSERT INTO users (name, email, role, password_hash) VALUES "
                   f"({q(name)}, {q(email)}, 'FREELANCER', {q(hash_password(PASSWORD))});")
    for name, email in CLIENTS:
        out.append(f"INSERT INTO users (name, email, role, password_hash) VALUES "
                   f"({q(name)}, {q(email)}, 'CLIENT', {q(hash_password(PASSWORD))});")
    out.append("")

    for name, desc, offset, status, freelancer, client in PROJECTS:
        deadline = TODAY + timedelta(days=offset)
        out.append("INSERT INTO projects (name, description, deadline, status, freelancer_id, client_id) VALUES "
                   f"({q(name)}, {q(desc)}, {q(deadline.isoformat())}, {q(status)}, {uid(freelancer)}, {uid(client)});")
    out.append("")

    for project, days_ago, hour, hours in TIME:
        start = stamp(days_ago, hour)
        end = start + timedelta(hours=hours)
        out.append("INSERT INTO time_entries (project_id, start_time, end_time) VALUES "
                   f"({pid(project)}, {q(start.strftime('%Y-%m-%d %H:%M:%S'))}, {q(end.strftime('%Y-%m-%d %H:%M:%S'))});")
    out.append("")

    owner = {p[0]: (p[4], p[5]) for p in PROJECTS}
    for project, kind, hours, rate, status, days_ago in INVOICES:
        freelancer, client = owner[project]
        created = (TODAY - timedelta(days=days_ago)).isoformat()
        out.append("INSERT INTO invoices (project_id, freelancer_id, client_id, invoice_type, hours, rate, status, created_date) VALUES "
                   f"({pid(project)}, {uid(freelancer)}, {uid(client)}, {q(kind)}, {hours}, {rate}, {q(status)}, {q(created)});")
    out.append("")

    for sender, receiver, text, days_ago, hour, was_read in MESSAGES:
        sent = stamp(days_ago, hour)
        read_at = q((sent + timedelta(hours=2)).strftime("%Y-%m-%d %H:%M:%S")) if was_read else "NULL"
        out.append("INSERT INTO messages (sender_id, receiver_id, content, sent_at, read_at) VALUES "
                   f"({uid(sender)}, {uid(receiver)}, {q(text)}, {q(sent.strftime('%Y-%m-%d %H:%M:%S'))}, {read_at});")

    target = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "database", "sample_data.sql")
    with open(target, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("Wrote", os.path.normpath(target))
    print("Demo logins (password", PASSWORD + "):")
    for _, email in FREELANCERS + CLIENTS:
        print("  ", email)


if __name__ == "__main__":
    main()
